// One-off build script: converts the raw world countries GeoJSON + ISO region
// mapping into per-country simplified GeoJSON files plus a static
// continent -> country-list and country -> continent map used by the app.
//
// Run with: node scripts/build-geo-data.cjs
// Inputs (download once, not committed to git):
//   Invoke-WebRequest -Uri "https://raw.githubusercontent.com/datasets/geo-countries/master/data/countries.geojson" -OutFile "scripts_countries_raw.geojson"
//   Invoke-WebRequest -Uri "https://raw.githubusercontent.com/lukes/ISO-3166-Countries-with-Regional-Codes/master/all/all.json" -OutFile "scripts_regions_raw.json"
const fs = require("fs");
const path = require("path");
const turf = require("@turf/turf");

const ROOT = path.join(__dirname, "..");
const countriesRaw = JSON.parse(
  fs.readFileSync(path.join(ROOT, "scripts_countries_raw.geojson"), "utf8")
);
const regionsRaw = JSON.parse(
  fs.readFileSync(path.join(ROOT, "scripts_regions_raw.json"), "utf8")
);

const REGION_TO_CONTINENT = {
  Asia: "Asia",
  Europe: "Europe",
  Africa: "Africa",
  Oceania: "Oceania",
  Americas: "Americas",
};

const iso3ToContinent = new Map();
for (const row of regionsRaw) {
  const continent = REGION_TO_CONTINENT[row.region];
  if (continent && row["alpha-3"]) {
    iso3ToContinent.set(row["alpha-3"], continent);
  }
}

const outCountriesDir = path.join(ROOT, "public", "geo", "countries");
const outContinentsDir = path.join(ROOT, "public", "geo", "continents");
fs.mkdirSync(outCountriesDir, { recursive: true });
fs.mkdirSync(outContinentsDir, { recursive: true });

const continentCountries = {
  Asia: [],
  Europe: [],
  Africa: [],
  Oceania: [],
  Americas: [],
};
const countryMeta = []; // { iso3, name, continent } for the picker UI
const continentMapEntries = [];
const continentFeatures = {
  Asia: [],
  Europe: [],
  Africa: [],
  Oceania: [],
  Americas: [],
};

let written = 0;
let skippedNoContinent = 0;

for (const feature of countriesRaw.features) {
  const iso3 = feature.properties["ISO3166-1-Alpha-3"];
  const name = feature.properties.name;
  if (!iso3 || iso3 === "-99") continue;

  const continent = iso3ToContinent.get(iso3);
  if (!continent) {
    skippedNoContinent += 1;
    continue;
  }

  // Simplify to keep per-country files small enough for mobile fetches.
  // Bigger/complex countries get a coarser tolerance; small ones stay precise.
  const approxArea = turf.area(feature); // m^2
  const tolerance = approxArea > 2_000_000_000_000 ? 0.05 : approxArea > 200_000_000_000 ? 0.02 : 0.005;

  let simplified;
  try {
    simplified = turf.simplify(feature, { tolerance, highQuality: false, mutate: false });
  } catch (err) {
    console.warn(`simplify failed for ${iso3} (${name}), using original geometry`, err.message);
    simplified = feature;
  }

  const outFeature = {
    type: "Feature",
    properties: { iso3, name, continent },
    geometry: simplified.geometry,
  };

  fs.writeFileSync(
    path.join(outCountriesDir, `${iso3}.geojson`),
    JSON.stringify(outFeature)
  );

  continentCountries[continent].push(iso3);
  countryMeta.push({ iso3, name, continent });
  continentMapEntries.push([iso3, continent]);
  continentFeatures[continent].push(outFeature);
  written += 1;
}

for (const [continent, features] of Object.entries(continentFeatures)) {
  const collection = { type: "FeatureCollection", features };
  fs.writeFileSync(
    path.join(outContinentsDir, `${continent}.geojson`),
    JSON.stringify(collection)
  );
}

for (const list of Object.values(continentCountries)) {
  list.sort();
}
countryMeta.sort((a, b) => a.name.localeCompare(b.name));

fs.writeFileSync(
  path.join(ROOT, "src", "data", "continentCountries.json"),
  JSON.stringify(continentCountries, null, 2)
);
fs.writeFileSync(
  path.join(ROOT, "src", "data", "countryMeta.json"),
  JSON.stringify(countryMeta, null, 2)
);

const continentMapTs = `// Auto-generated by scripts/build-geo-data.cjs — do not edit by hand.
export type Continent = "Asia" | "Europe" | "Africa" | "Oceania" | "Americas";

export const COUNTRY_TO_CONTINENT: Record<string, Continent> = {
${continentMapEntries.map(([iso3, continent]) => `  ${iso3}: "${continent}",`).join("\n")}
};
`;
fs.writeFileSync(path.join(ROOT, "src", "lib", "geo", "continentMap.ts"), continentMapTs);

console.log(`Wrote ${written} country files, skipped ${skippedNoContinent} without a mapped continent.`);
for (const [continent, list] of Object.entries(continentCountries)) {
  console.log(`  ${continent}: ${list.length} countries`);
}
